    public static string ResolveSupabaseUrl(string? configValue)
    {
        if (!string.IsNullOrWhiteSpace(configValue))
            return configValue.Trim();

        return Deobfuscate(ObfuscatedUrlBytes);
    }

    public static string ResolveSupabaseKey(string? configValue)
    {
        if (!string.IsNullOrWhiteSpace(configValue))
            return configValue.Trim();

        return Deobfuscate(ObfuscatedKeyBytes);
    }

    public static string Deobfuscate(byte[]? cipherBytes)
    {
        if (cipherBytes == null || cipherBytes.Length == 0)
            return string.Empty;

        var result = new byte[cipherBytes.Length];
        for (var i = 0; i < cipherBytes.Length; i++)
        {
            result[i] = (byte)(cipherBytes[i] ^ Mask[i % Mask.Length] ^ (byte)(i * 3 % 256));
        }

        return Encoding.UTF8.GetString(result);
    }
